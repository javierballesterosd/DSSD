-- RescueSync: migración NO destructiva para pasar el avance de las actividades de la emergencia a cada oferta.
-- Antes: actividad.finalizada (un solo estado por actividad). Ahora: actividad_oferta, una fila por actividad y por
-- oferta adjudicada con recursos; las ONGs de un consorcio comparten la fila de su oferta.
-- Es idempotente. Correrlo con el contenedor postgres_db levantado y, de preferencia, con el backend detenido:
--   docker exec -i postgres_db psql -U postgres -d rescuesync < db/seed/03-actividades-por-oferta.sql
-- (Si se corrió 01-reset-y-seed.sql este script no hace falta: ya parte de una base vacía.)

BEGIN;

CREATE TABLE IF NOT EXISTS actividad_oferta (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  actividad_id bigint NOT NULL REFERENCES actividad (id),
  oferta_id bigint NOT NULL REFERENCES oferta (id),
  finalizada boolean NOT NULL DEFAULT false,
  fecha_finalizacion timestamp,
  usuario_finalizacion varchar(150),
  ong_finalizacion_id bigint REFERENCES ong (id),
  CONSTRAINT uk_actividad_oferta UNIQUE (actividad_id, oferta_id)
);

-- Una fila por cada actividad de la emergencia y cada oferta adjudicada (o ya en ejecución o finalizada) que tenga
-- al menos un recurso aceptado. Conserva lo ya marcado como hecho si todavía existe la columna vieja.
DO $$
DECLARE
  hay_columna boolean;
BEGIN
  SELECT EXISTS (
    SELECT 1 FROM information_schema.columns
    WHERE table_name = 'actividad' AND column_name = 'finalizada'
  ) INTO hay_columna;

  EXECUTE format($sql$
    INSERT INTO actividad_oferta (actividad_id, oferta_id, finalizada, fecha_finalizacion)
    SELECT a.id, o.id, %s, NULL
    FROM oferta o
    JOIN lote l ON l.id = o.lote_id
    JOIN actividad a ON a.emergencia_id = l.emergencia_id
    WHERE o.estado IN ('ADJUDICADA', 'EN_EJECUCION', 'FINALIZADA')
      AND EXISTS (SELECT 1 FROM detalle_oferta d WHERE d.oferta_id = o.id AND COALESCE(d.cantidad_aceptada, 0) > 0)
    ON CONFLICT (actividad_id, oferta_id) DO NOTHING
  $sql$, CASE WHEN hay_columna THEN 'a.finalizada' ELSE 'false' END);
END $$;

-- Hibernate no borra la columna vieja y es NOT NULL: rompería el alta de emergencias y actividades nuevas.
ALTER TABLE actividad DROP COLUMN IF EXISTS finalizada;

COMMIT;
